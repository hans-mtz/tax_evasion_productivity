## Stage-2 ELVIS driver -----------------------------------------------------
## theta = (lambda, delta0, delta1, delta2, sigma2_psi), unincorp firms only,
## moment system from Paper/sections/9999-elvis.qmd "Applying ELVIS to stage
## 2 alone" + CLAUDE.md's 2026-08-28 "Stage-2 moment system, finalized" entry
## (15 moments, see Code/Rcpp/1200-stage2-elvis.cpp's header for the full
## list). Compiled worker does the per-firm Metropolis-tilted-average
## simulation (mh_tilted_average_cpp); everything else (CUE objective, BOBYQA
## search, the lambda grid) is R, following AK2020's own split (NLopt/BOBYQA
## for the smooth block, theta's "difficult" dimension gridded).
##
## lambda is gridded, not searched directly, because it's the one parameter
## that changes the SUPPORT of the latent M (not just a smooth reweighting):
## feasibility requires M*_it > 1/(2*lambda) for every firm used at that grid
## point -- (delta0,delta1,delta2,sigma2_psi,gamma) is the smooth block,
## jointly optimized via BOBYQA for each lambda.
##
## 2026-08-28 moment-system redesign: dropped the psi*lag_k/psi*lag_l/psi*
## (cross-instrument) spare-instrument rows entirely (Z_CANDIDATES, the old
## z_cols machinery) -- replaced by psi*ln(M)/psi*(ln M)^2 (more direct: M is
## "true inputs" itself, not a proxy, and no observations lost to lagging),
## plus a new eps-heterogeneity block (rows 7-10 in the .cpp, matched to each
## firm's own sic_3 via Code/Products/1206-stage2-eps-targets.RData -- CORP
## epsilon's variance is NOT homogeneous across industries, Bartlett K^2=920,
## p<2e-16, so a single pooled target would misspecify most industries), and
## a new sigma2_psi nuisance parameter (rows 11-14, a heteroskedasticity-in-
## psi block). d_g is now a fixed 15 (was 1+length(z_cols)+3=7), and the
## smooth block grew from 3 to 4 parameters. See CLAUDE.md for the full
## design discussion and what was considered and dropped (psi*e; the
## redundant psi*(eps^2-var) alongside psi*eps_c^2).
##
## corner_mode ("drop" vs "include_zero"), added 2026-08-27: tau_P_it==0
## firms (~10% of unincorp obs) are a genuine MB(e)=0-for-every-e corner, not
## data noise. "drop" excludes them entirely. "include_zero" keeps them with
## a known M=Mstar (e=0) contributing only the psi-free rows (eps*om and the
## eps-only CORP-target rows) -- see the .cpp header for exactly which rows.
##
## Random-number handling in the C++ worker (2026-08-27): each firm's WHOLE
## random sequence is generated by a C++-side RNG reseeded per firm as
## base_seed+row_id -- identical across every (theta,gamma) evaluation. The
## chain also discards an initial n_burn steps before averaging over n_keep.

